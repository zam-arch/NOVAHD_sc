/* Runtime for the recompiled N.O.V.A. HD executable (iOS 3.2, armv6): game memory, imports, threads, and the
 * iOS platform (Objective-C runtime, Foundation, UIKit, ...).
 *
 * Game memory is one 4 GB reservation; a game address is an offset into it (rt_mem). The executable sits at its
 * link addresses (0x1000-0x402000; __PAGEZERO stays unmapped). The translated code (tools/recomp/lift.py) calls
 * rc_import for the executable's imports and rc_dispatch for computed targets; rc_dispatch sends addresses in
 * the host-function range to rc_hostcall, which is how game code calls runtime functions through pointers
 * (Objective-C methods of system classes, callbacks, thread entry returns).
 *
 * Calling convention (iOS ARM, softfp): arguments in r0-r3, then the stack; 64-bit values are only 4-byte
 * aligned (unlike AAPCS); structs larger than 4 bytes are returned through a hidden pointer in r0.
 */
